create table public.audit_logs (
  id bigint generated by default as identity primary key,
  actor_id uuid references public.profiles (id) on delete set null,
  action text not null,
  entity_type text not null,
  entity_id text not null,
  outcome text not null,
  metadata jsonb not null default '{}'::jsonb,
  request_id uuid,
  occurred_at timestamptz not null default now(),
  constraint audit_logs_action_check check (action = btrim(action) and action <> ''),
  constraint audit_logs_entity_type_check
    check (entity_type = btrim(entity_type) and entity_type <> ''),
  constraint audit_logs_entity_id_check
    check (entity_id = btrim(entity_id) and entity_id <> ''),
  constraint audit_logs_outcome_check check (outcome = btrim(outcome) and outcome <> ''),
  constraint audit_logs_metadata_check check (jsonb_typeof(metadata) = 'object')
);

