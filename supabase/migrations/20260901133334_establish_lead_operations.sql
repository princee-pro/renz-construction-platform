create table public.lead_stages (
  id smallint generated by default as identity primary key,
  key text not null unique,
  label text not null,
  sort_order integer not null default 0,
  is_terminal boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  created_by uuid references public.profiles (id) on delete set null,
  updated_by uuid references public.profiles (id) on delete set null,
  version integer not null default 1,
  constraint lead_stages_key_check
    check (key = btrim(key) and key ~ '^[a-z][a-z0-9]*(?:[._-][a-z0-9]+)*$'),
  constraint lead_stages_label_check check (label = btrim(label) and label <> ''),
  constraint lead_stages_sort_order_check check (sort_order >= 0),
  constraint lead_stages_version_check check (version > 0)
);

