create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  display_name text,
  account_status text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  version integer not null default 1,
  constraint profiles_display_name_trimmed_check
    check (display_name is null or (display_name = btrim(display_name) and display_name <> '')),
  constraint profiles_account_status_trimmed_check
    check (account_status is null or (account_status = btrim(account_status) and account_status <> '')),
  constraint profiles_version_check check (version > 0)
);

create table public.roles (
  id smallint generated by default as identity primary key,
  key text not null unique,
  display_name text not null,
  is_system boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  created_by uuid references public.profiles (id) on delete set null,
  updated_by uuid references public.profiles (id) on delete set null,
  version integer not null default 1,
  constraint roles_key_check
    check (key = btrim(key) and key ~ '^[a-z][a-z0-9]*(?:[._-][a-z0-9]+)*$'),
  constraint roles_display_name_check
    check (display_name = btrim(display_name) and display_name <> ''),
  constraint roles_version_check check (version > 0)
);

create table public.permissions (
  id smallint generated by default as identity primary key,
  key text not null unique,
  display_name text not null,
  description text,
  is_system boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  created_by uuid references public.profiles (id) on delete set null,
  updated_by uuid references public.profiles (id) on delete set null,
  version integer not null default 1,
  constraint permissions_key_check
    check (key = btrim(key) and key ~ '^[a-z][a-z0-9]*(?:[._-][a-z0-9]+)*$'),
  constraint permissions_display_name_check
    check (display_name = btrim(display_name) and display_name <> ''),
  constraint permissions_description_trimmed_check
    check (description is null or (description = btrim(description) and description <> '')),
  constraint permissions_version_check check (version > 0)
);

create table public.role_permissions (
  role_id smallint not null references public.roles (id) on delete restrict,
  permission_id smallint not null references public.permissions (id) on delete restrict,
  granted_at timestamptz not null default now(),
  granted_by uuid references public.profiles (id) on delete set null,
  primary key (role_id, permission_id)
);

create table public.user_roles (
  user_id uuid not null references public.profiles (id) on delete cascade,
  role_id smallint not null references public.roles (id) on delete restrict,
  granted_at timestamptz not null default now(),
  granted_by uuid references public.profiles (id) on delete set null,
  primary key (user_id, role_id)
);

